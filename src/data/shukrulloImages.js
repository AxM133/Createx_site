const files = import.meta.glob(
  '../components/assets/images/shukrullo/**/*.{png,jpg,jpeg,svg,webp,gif}',
  { eager: true },
);

const stem = (path) => path.split('/').pop().replace(/\.[^.]+$/, '').toLowerCase();

const mk = (name, hint = 'ТУТ ДОЛЖНА БЫТЬ КАРТИНКА') => {
  const key = Object.keys(files).find((k) => stem(k) === name.toLowerCase());
  return { src: key ? files[key].default : `/missing/${name}`, hint };
};
